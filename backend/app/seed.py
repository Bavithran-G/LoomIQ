def _at(d, hour=10):
    return datetime.combine(d, time(hour, 0), tzinfo=timezone.utc)


class Backdater:
    """Moves timestamps of rows created since the last mark to a given historical day."""
    TABLES = [(Event, "created_at"), (RollEvent, "created_at"), (StockMovement, "created_at"),
              (CostEntry, "created_at"), (Inspection, "created_at"), (Roll, "created_at")]

    def __init__(self, db):
        self.db = db
        self.marks = {}
        self.mark()

    def mark(self):
        self.db.flush()
        for model, _ in self.TABLES:
            self.marks[model] = self.db.scalar(select(model.id).order_by(model.id.desc()).limit(1)) or 0

    def to(self, d, hour=10):
        self.db.flush()
        ts = _at(d, hour)
        for model, col in self.TABLES:
            self.db.execute(update(model).where(model.id > self.marks[model]).values({col: ts}))
        self.db.execute(update(Inspection).where(Inspection.id > self.marks[Inspection],
                                                 Inspection.reviewed_at.isnot(None)).values(reviewed_at=ts + timedelta(hours=1)))
        self.db.execute(update(Inspection).where(Inspection.id > self.marks[Inspection],
                                                 Inspection.inferred_at.isnot(None)).values(inferred_at=ts))
        self.mark()


def migrate():
    from pathlib import Path
    from alembic import command
    from alembic.config import Config
    root = Path(__file__).resolve().parent.parent
    cfg = Config(str(root / "alembic.ini"))
    cfg.set_main_option("script_location", str(root / "migrations"))
    command.upgrade(cfg, "head")


def reset():
    with engine.begin() as conn:
        if engine.dialect.name == "postgresql":
            conn.execute(text("DROP SCHEMA public CASCADE; CREATE SCHEMA public;"))
        else:
            Base.metadata.drop_all(conn)
            conn.execute(text("DROP TABLE IF EXISTS alembic_version"))
    migrate()


